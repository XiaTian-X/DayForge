    private val armedFault = AtomicReference<ReplacementSqlFault?>()
    /** Fixed native fault below the controlled wrapper; never returns its raw handle. */
    private inner class ReplacementFaultFactory : androidx.sqlite.db.SupportSQLiteOpenHelper.Factory {
        private var original: androidx.sqlite.db.SupportSQLiteDatabase? = null
        private var wrapped: androidx.sqlite.db.SupportSQLiteDatabase? = null
        private fun wrap(raw: androidx.sqlite.db.SupportSQLiteDatabase): androidx.sqlite.db.SupportSQLiteDatabase {
            if (original !== raw) {
                original = raw
                wrapped = object : androidx.sqlite.db.SupportSQLiteDatabase by raw {

                    override fun compileStatement(sql: String): androidx.sqlite.db.SupportSQLiteStatement {
                        val native = raw.compileStatement(sql)
                        return object : androidx.sqlite.db.SupportSQLiteStatement by native {
                            private val args = sortedMapOf<Int, Any?>()
                            override fun bindNull(index: Int) { args[index] = null; native.bindNull(index) }
                            override fun bindLong(index: Int, value: Long) { args[index] = value; native.bindLong(index, value) }
                            override fun bindDouble(index: Int, value: Double) { args[index] = value; native.bindDouble(index, value) }
                            override fun bindString(index: Int, value: String) { args[index] = value; native.bindString(index, value) }
                            override fun bindBlob(index: Int, value: ByteArray) { args[index] = value.copyOf(); native.bindBlob(index, value) }
                            override fun clearBindings() { args.clear(); native.clearBindings() }
                            private fun beforeExecute() {
                                val sqlQuery = sql
                                val bindArgs = args.values.toList()
                                val fault = armedFault.get() ?: return
                                val text = sqlQuery.trim().lowercase(Locale.ROOT).replace("`", "").replace(Regex("\\s+"), " ")
                                val matches = when (fault.point) {
                                    // Exact INSERT forms generated by the current Room adapters.
                                    ReplacementFaultPoint.LINK -> text.startsWith("insert or replace into habit_metric_links (")
                                    ReplacementFaultPoint.ORIGIN -> text.startsWith("insert or abort into next_request_origins (")
                                    ReplacementFaultPoint.DEFERRED_COMMIT -> text ==
                                        "update next_config_imports set state='local_committed',receipthash=? " +
                                        "where importid=? and mode='replacement' and state='prepared'"
                                }
                                if (!matches || !armedFault.compareAndSet(fault, null)) return
                                // Runs immediately before the actual fixed native statement, outside diagnostic callbacks.
                                // Retain independent setup observations; the original statement/COMMIT must fail.
                                fault.reached.set(true)
                                fault.setupFailure.set(runCatching {
                                    fault.transactionObserved.set(db.inTransaction() && raw.inTransaction())
                                    if (!fault.transactionObserved.get()) return@runCatching
                                    val phase = state(fault.importId)
                                    fault.phaseObserved.set(phase)
                                    val expected = if (fault.point == ReplacementFaultPoint.ORIGIN) "local_committed" else "prepared"
                                    if (phase != expected) return@runCatching
                                    if (fault.point == ReplacementFaultPoint.DEFERRED_COMMIT) {
                                        fault.bindingsObserved.set(bindArgs.size == 2 && bindArgs[1] == fault.importId)
                                        if (!fault.bindingsObserved.get()) return@runCatching
                                        // DEFERRABLE INITIALLY DEFERRED: this INSERT returns normally. Only the
                                        // actual outer COMMIT may raise the deferred foreign-key violation.
                                        raw.compileStatement("INSERT INTO replacement_deferred VALUES(99)").use { check(it.executeInsert() > 0L) }
                                    } else {
                                        // The table and both triggers were fixed BEFORE preview. Activate only at
                                        // the real target SQL, after fingerprint checks, in that same transaction.
                                        raw.compileStatement("INSERT INTO replacement_fault_gate(point) VALUES(?)").use {
                                            it.bindString(1, fault.point.name); check(it.executeInsert() > 0L)
                                        }
                                    }
                                    fault.nativeSetupReturned.set(true)
                                }.exceptionOrNull())
                            }
                            override fun execute() { beforeExecute(); native.execute() }
                            override fun executeInsert(): Long { beforeExecute(); return native.executeInsert() }
                            override fun executeUpdateDelete(): Int { beforeExecute(); return native.executeUpdateDelete() }
                        }
                    }

                }
            }
            return requireNotNull(wrapped)
        }
        override fun create(configuration: androidx.sqlite.db.SupportSQLiteOpenHelper.Configuration): androidx.sqlite.db.SupportSQLiteOpenHelper {
            val parent = configuration.callback
            val callbacks = object : androidx.sqlite.db.SupportSQLiteOpenHelper.Callback(parent.version) {
                override fun onConfigure(db: androidx.sqlite.db.SupportSQLiteDatabase) = parent.onConfigure(wrap(db))
                override fun onCreate(db: androidx.sqlite.db.SupportSQLiteDatabase) = parent.onCreate(wrap(db))
                override fun onUpgrade(db: androidx.sqlite.db.SupportSQLiteDatabase, oldVersion: Int, newVersion: Int) =
                    parent.onUpgrade(wrap(db), oldVersion, newVersion)
                override fun onDowngrade(db: androidx.sqlite.db.SupportSQLiteDatabase, oldVersion: Int, newVersion: Int) =
                    parent.onDowngrade(wrap(db), oldVersion, newVersion)
                override fun onOpen(db: androidx.sqlite.db.SupportSQLiteDatabase) {
                    val started = android.os.SystemClock.elapsedRealtime()
                    var completed = false
                    android.util.Log.i("ConfigOpen", "Starting wrapped onOpen callback")
                    try { parent.onOpen(wrap(db)); completed = true }
                    finally { android.util.Log.i("ConfigOpen", "${if (completed) "Completed" else "Failed"} wrapped onOpen callback in " +
                        "${android.os.SystemClock.elapsedRealtime() - started}ms") }
                }
                override fun onCorruption(db: androidx.sqlite.db.SupportSQLiteDatabase) = parent.onCorruption(wrap(db))
            }
            val native = androidx.sqlite.db.framework.FrameworkSQLiteOpenHelperFactory().create(
                androidx.sqlite.db.SupportSQLiteOpenHelper.Configuration.builder(configuration.context)
                    .name(configuration.name).callback(callbacks).noBackupDirectory(configuration.useNoBackupDirectory).build())
            return object : androidx.sqlite.db.SupportSQLiteOpenHelper by native {
                override val writableDatabase get() = wrap(native.writableDatabase)
                override val readableDatabase get() = wrap(native.readableDatabase)
            }
        }
    }
