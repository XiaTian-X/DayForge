    private fun requireFaultReached(fault: ReplacementSqlFault) {
        assertTrue("Must reach the real ${fault.point} SQL, not an earlier preview gate", fault.reached.get())
        assertNull("Observer setup must complete without an unpropagated exception", fault.setupFailure.get())
        assertTrue("Fault must execute inside the real replacement transaction", fault.transactionObserved.get())
        assertEquals("Fault must reach its declared business/receipt phase",
            if (fault.point == ReplacementFaultPoint.ORIGIN) "local_committed" else "prepared", fault.phaseObserved.get())
        if (fault.point == ReplacementFaultPoint.DEFERRED_COMMIT)
            assertTrue("Receipt UPDATE must address this original import", fault.bindingsObserved.get())
        assertTrue("Native fault setup must return before the business failure", fault.nativeSetupReturned.get())
    }

    /** A fault table is intentionally added after initial onOpen. Stabilize through the real
     * cold-open callback BEFORE confirming the replacement fingerprint. This is not a changed
     * baseline allowance: prove the exact missing guards and the owner's one dirty transition.
     */
    private suspend fun stabilizeFaultFences(tables: Set<String>) {
        require(tables == setOf("replacement_fault_gate") ||
            tables == setOf("replacement_parent", "replacement_deferred"))
        val before = databaseImage()
        val beforeSchema = before.contents.getValue("schema").jsonArray
        fun cell(type: Int, value: JsonElement) = buildJsonObject {
            put("sqlite_type", type); put("value", value)
        }
        fun text(value: String) = cell(android.database.Cursor.FIELD_TYPE_STRING, JsonPrimitive(value))
        fun integer(value: Long) = cell(android.database.Cursor.FIELD_TYPE_INTEGER, JsonPrimitive(value))
        val guards = buildMap<String, JsonObject> {
            for (table in tables) for (action in listOf("INSERT", "UPDATE", "DELETE")) {
                val name = "replica_fence_${table}_${action.lowercase(Locale.ROOT)}"
                val definition = "CREATE TRIGGER $name\n" +
                    "BEFORE $action ON `$table` WHEN EXISTS(SELECT 1 FROM next_replica_fence WHERE id IS NOT 1 OR mode IS NOT 'closed')\n" +
                    "BEGIN SELECT RAISE(ABORT,'SYNC_REPLICA_SWITCH_FENCED'); END"
                put(name, buildJsonObject {
                    put("type", text("trigger")); put("name", text(name)); put("tbl_name", text(table))
                    put("rootpage", integer(0L)); put("sql", text(definition))
                })
            }
        }
        fun schemaName(row: JsonElement) = row.jsonObject.getValue("name").jsonObject.getValue("value").jsonPrimitive.content
        assertTrue("The isolated fault tables must start without these guards",
            beforeSchema.none { schemaName(it) in guards })
        val oldTables = before.contents.getValue("tables").jsonObject
        tables.forEach { assertTrue(oldTables.containsKey(it)); assertTrue(oldTables.getValue(it).jsonArray.isEmpty()) }
        val control = oldTables.getValue("count_trust_control").jsonArray.single().jsonObject
        assertEquals(setOf("__recovery_rowid", "id", "storageId", "generation", "dirty"), control.keys)
        assertEquals(integer(1L), control.getValue("__recovery_rowid")); assertEquals(integer(1L), control.getValue("id"))
        val storageId = control.getValue("storageId").jsonObject.getValue("value").jsonPrimitive.content
        assertTrue(isContractUuid(storageId)); assertEquals(text(storageId), control.getValue("storageId"))
        val generation = control.getValue("generation").jsonObject.getValue("value").jsonPrimitive.long
        assertTrue(generation >= 0 && generation < Long.MAX_VALUE)
        assertEquals(integer(generation), control.getValue("generation"))
        assertTrue(control.getValue("dirty") in setOf(integer(0L), integer(1L)))
        storage.reopen()
        val after = databaseImage() // First real cold SQL opens and executes the production callback.
        val afterSchema = after.contents.getValue("schema").jsonArray
        val added = afterSchema.filter { schemaName(it) in guards }
        assertEquals(guards.size, added.size)
        assertEquals(guards, added.associate { schemaName(it) to it.jsonObject })
        assertEquals("No original schema field, SQL text or rootpage may change",
            beforeSchema, JsonArray(afterSchema.filterNot { schemaName(it) in guards }))
        val newControl = JsonObject(control + mapOf("generation" to integer(generation + 1), "dirty" to integer(1L)))
        val expectedTables = JsonObject(oldTables + ("count_trust_control" to JsonArray(listOf(newControl))))
        assertEquals("Only the exact observed-schema dirty transition is allowed", expectedTables,
            after.contents.getValue("tables"))
        assertEquals(before.contents - setOf("schema", "tables"), after.contents - setOf("schema", "tables"))
    }

    private suspend fun databaseImage() = db.withTransaction { NextReplicaStorageProof(db).readInTransaction() }
    private suspend fun databaseImageHash() = databaseImage().hash

    /** Diagnostics reuse the two original complete proof values; no extra SQL, changed proof
     * scope, ignored columns or replacement for the full hash assertion. No row values leak to
     * logs: report only native table/column names, row counts, hashes and bounded difference loci.
     */
    private fun imageDifference(before: ReplicaStorageProof, after: ReplicaStorageProof): String {
        if (before.hash == after.hash) return "Complete native storage image is unchanged"
        fun hash(value: JsonElement?) = value?.let { syncPayloadHash(it.toString()) } ?: "absent"
        fun firstDifference(left: JsonArray?, right: JsonArray?): String {
            val a = left ?: JsonArray(emptyList()); val b = right ?: JsonArray(emptyList())
            val index = (0 until maxOf(a.size, b.size)).firstOrNull { a.getOrNull(it) != b.getOrNull(it) }
                ?: return "none"
            val old = a.getOrNull(index) as? JsonObject; val fresh = b.getOrNull(index) as? JsonObject
            val columns = ((old?.keys ?: emptySet()) + (fresh?.keys ?: emptySet())).sorted()
                .filter { old?.get(it) != fresh?.get(it) }
            return "row_index=$index columns=${columns.take(32)} remaining_columns=${maxOf(0, columns.size - 32)}"
        }
        val oldTables = before.contents.getValue("tables").jsonObject
        val newTables = after.contents.getValue("tables").jsonObject
        val tables = (oldTables.keys + newTables.keys).sorted().filter { oldTables[it] != newTables[it] }
        val schemaBefore = before.contents.getValue("schema").jsonArray
        val schemaAfter = after.contents.getValue("schema").jsonArray
        return buildString {
            append("Complete image mismatch; user_version=")
            append(before.contents["user_version"]); append(" -> "); append(after.contents["user_version"])
            append("; schema_hash="); append(hash(schemaBefore)); append(" -> "); append(hash(schemaAfter))
            if (schemaBefore != schemaAfter) { append("; schema_"); append(firstDifference(schemaBefore, schemaAfter)) }
            append("; changed_tables="); append(tables)
            for (table in tables) {
                val old = oldTables[table] as? JsonArray; val fresh = newTables[table] as? JsonArray
                append("; "); append(table); append(" rows="); append(old?.size); append(" -> "); append(fresh?.size)
                append(" hash="); append(hash(old)); append(" -> "); append(hash(fresh))
                append(' '); append(firstDifference(old, fresh))
            }
        }
    }

